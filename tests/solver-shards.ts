/**
 * Разбиение кампании на шарды решателя. Полный BFS-прогон по всем уровням не
 * влезает в один тест-файл по времени, поэтому уровни поделены на группы —
 * `levels-solver-1..N.test.ts`.
 *
 * Реестр вынесен сюда, чтобы `levels.test.ts` мог доказать: каждый уровень
 * попал ровно в один шард. Без этой проверки уровень, добавленный вне уже
 * описанных диапазонов id, молча остался бы без доказательства проходимости и
 * без сверки `par` с оптимумом — то есть нарушил бы правило проекта незаметно.
 */
export interface SolverShard {
  /** Хвост заголовка describe: «решатель <title>». */
  title: string;
  match(id: number): boolean;
}

export const SOLVER_SHARDS: SolverShard[] = [
  { title: 'уровней 1–50', match: (id) => id >= 1 && id <= 50 },
  { title: 'уровней 51–81', match: (id) => id >= 51 && id <= 81 },
  { title: 'уровней 82–92', match: (id) => id >= 82 && id <= 92 },
  { title: 'уровня 93', match: (id) => id === 93 },
  { title: 'уровней 94–100', match: (id) => id >= 94 && id <= 100 }
];
